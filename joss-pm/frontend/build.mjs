// Dependency-free vendor bundler: packs React 19 + ReactDOM client (production builds) into ONE browser ES module,
// because npm registry access / vite are unavailable in this environment.  Usage: node build.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const NM = process.env.NODE_MODULES || "/opt/afs-node/node_modules";
const req = createRequire(path.join(NM, "x.js"));
const mods = new Map();   // abs path -> id

function resolve(from, spec) {
  if (spec.startsWith(".")) return req.resolve(path.resolve(path.dirname(from), spec));
  return req.resolve(spec);
}
function add(file) {
  if (mods.has(file)) return;
  mods.set(file, { id: mods.size, code: "", deps: {} });
  let code = fs.readFileSync(file, "utf8");
  const rec = mods.get(file);
  if (/\.development\.js$/.test(file)) { rec.code = "module.exports = {};"; return; }   // dead branch in production
  code = code.replace(/process\.env\.NODE_ENV/g, '"production"');
  rec.code = code;
  for (const m of code.matchAll(/\brequire\(\s*["']([^"']+)["']\s*\)/g)) {
    const spec = m[1];
    let abs;
    try { abs = resolve(file, spec); } catch { continue; }
    if (!abs.startsWith(NM)) continue;
    rec.deps[spec] = abs;
    add(abs);
  }
}
const SSR = process.argv.includes("--ssr");   // test-only bundle that also exports renderToString
const entries = { react: req.resolve("react"), "react-dom/client": req.resolve("react-dom/client") };
if (SSR) entries["react-dom/server"] = req.resolve("react-dom/server.browser");
for (const f of Object.values(entries)) add(f);

let out = "// GENERATED by build.mjs - React " + req("react/package.json").version + " (production)\n";
out += "const __defs = {\n";
for (const [file, rec] of mods) {
  out += `${rec.id}: [function(module, exports, require){\n${rec.code}\n}, ${JSON.stringify(Object.fromEntries(Object.entries(rec.deps).map(([k, v]) => [k, mods.get(v).id])))}],\n`;
}
out += "};\nconst __cache = {};\nfunction __load(id){ if(__cache[id]) return __cache[id].exports; const m=__cache[id]={exports:{}}; const [fn,deps]=__defs[id]; fn(m,m.exports,(s)=>{ if(!(s in deps)) throw new Error('vendor: cannot require '+s); return __load(deps[s]); }); return m.exports; }\n";
out += `const React = __load(${mods.get(entries.react).id});\nconst ReactDOMClient = __load(${mods.get(entries["react-dom/client"]).id});\n`;
if (SSR) out += `const ReactDOMServer = __load(${mods.get(entries["react-dom/server"]).id});\nexport const renderToString = ReactDOMServer.renderToString;\n`;
out += "export default React;\nexport { ReactDOMClient };\n";
const reactNames = Object.keys(req("react")).filter(k => /^[A-Za-z_$][\w$]*$/.test(k));
out += `export const { ${reactNames.join(", ")} } = React;\n`;
out += "export const { createRoot, hydrateRoot } = ReactDOMClient;\n";
const outFile = SSR ? "test/.ssr/vendor/react.js" : "vendor/react.js";
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, "var process={env:{NODE_ENV:'production'}};\n" + out);
console.log(outFile, (out.length / 1024).toFixed(0) + " KB,", mods.size, "modules");
